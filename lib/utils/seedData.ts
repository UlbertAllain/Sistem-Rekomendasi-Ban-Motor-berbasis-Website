export async function seedTires(): Promise<{ success: boolean; count: number; errors: string[]; skipped: number }> {
  const errors: string[] = []; let count = 0; let skipped = 0;
  let existingTires: string[] = [];
  try { const db = getAdminDb(); if (db) { const snapshot = await db.collection("tires").get(); existingTires = snapshot.docs.map((doc) => doc.data().fullName as string); } } catch { /* skip */ }
  for (const tire of SEED_TIRES) { if (existingTires.includes(tire.fullName)) { skipped++; continue; } try { await addTire(tire); count++; } catch (err: unknown) { const msg = err instanceof Error ? err.message : "Unknown error"; errors.push(`Gagal seed ${tire.fullName}: ${msg}`); } }
  return { success: errors.length === 0, count, errors, skipped };
}

export async function seedMotorcycles(): Promise<{ success: boolean; count: number; errors: string[]; skipped: number }> {
  const errors: string[] = []; let count = 0; let skipped = 0;
  let existingMotorcycles: string[] = [];
  try { const db = getAdminDb(); if (db) { const snapshot = await db.collection("motorcycles").get(); existingMotorcycles = snapshot.docs.map((doc) => doc.data().fullName as string); } } catch { /* skip */ }
  for (const moto of SEED_MOTORCYCLES) { if (existingMotorcycles.includes(moto.fullName)) { skipped++; continue; } try { await addMotorcycle(moto); count++; } catch (err: unknown) { const msg = err instanceof Error ? err.message : "Unknown error"; errors.push(`Gagal seed ${moto.fullName}: ${msg}`); } }
  return { success: errors.length === 0, count, errors, skipped };
}

export async function seedAll(): Promise<void> {
  console.log("Seeding tires..."); const tireResult = await seedTires(); console.log(`Tires: ${tireResult.count} ditambahkan, ${tireResult.skipped} sudah ada, ${tireResult.errors.length} gagal`);
  console.log("Seeding motorcycles..."); const motoResult = await seedMotorcycles(); console.log(`Motorcycles: ${motoResult.count} ditambahkan, ${motoResult.skipped} sudah ada, ${motoResult.errors.length} gagal`);
  console.log("Seed complete!");
}

export async function clearAllData(): Promise<void> {
  const db = getAdminDb(); if (!db) throw new Error("Database belum dikonfigurasi");
  const tireBatch = db.batch(); const tireSnapshot = await db.collection("tires").get(); tireSnapshot.docs.forEach((doc) => tireBatch.delete(doc.ref)); await tireBatch.commit(); console.log(`Deleted ${tireSnapshot.size} tires`);
  const motoBatch = db.batch(); const motoSnapshot = await db.collection("motorcycles").get(); motoSnapshot.docs.forEach((doc) => motoBatch.delete(doc.ref)); await motoBatch.commit(); console.log(`Deleted ${motoSnapshot.size} motorcycles`);
}